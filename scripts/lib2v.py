#!/usr/bin/env python3
"""
Generate zero-delay Verilog simulation models from a Liberty file, for
gate-level simulation of the synthesized netlists.

  * combinational cells: one `assign` per output from its `function`
  * flip-flops: `ff` group with next_state / clocked_on / optional clear, preset
  * cells without a function (fillers, antenna, latches, ...) are skipped

Usage: python scripts/lib2v.py liberty/nangate45_typ.lib build/cells.v
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sta import parse_liberty  # noqa: E402


def expr(f):
    # Liberty boolean syntax is already Verilog-compatible except for these
    return f.replace("*", "&").replace("+", "|")


def main():
    lib_path, out_path = sys.argv[1], sys.argv[2]
    lib = parse_liberty(lib_path)
    out = ["// Generated by scripts/lib2v.py from %s - do not edit" % os.path.basename(lib_path),
           "`timescale 1ns/1ps", ""]
    n = 0
    for cg in lib.sub("cell"):
        pins = cg.sub("pin")
        ins = [p.args[0] for p in pins if p.attrs.get("direction") == "input"]
        outs = [p for p in pins if p.attrs.get("direction") == "output"]
        if not outs or cg.sub("latch") or cg.sub("statetable"):
            continue
        ffs = cg.sub("ff")
        if any("function" not in p.attrs for p in outs):
            continue
        if ffs and len(ffs) != 1:
            continue
        name = cg.args[0]
        ports = ins + [p.args[0] for p in outs]
        body = ["module %s (%s);" % (name, ", ".join(ports))]
        body += ["    input  %s;" % p for p in ins]
        body += ["    output %s;" % p.args[0] for p in outs]
        if ffs:
            ff = ffs[0]
            iq, iqn = ff.args[0], ff.args[1]
            clk = ff.attrs["clocked_on"]
            if clk.startswith("!") or " " in clk:
                continue  # only plain rising-edge flops are needed here
            nxt = expr(ff.attrs["next_state"])
            clr = ff.attrs.get("clear")
            pre = ff.attrs.get("preset")
            body.append("    reg %s;" % iq)
            body.append("    wire %s = ~%s;" % (iqn, iq))
            sens = ["posedge %s" % clk]
            # active-low async pins appear as "!RN" in the liberty clear/preset
            for sig in (clr, pre):
                if sig:
                    pin = sig.lstrip("!")
                    sens.append(("negedge " if sig.startswith("!") else "posedge ") + pin)
            body.append("    always @(%s)" % " or ".join(sens))
            cond = []
            if clr:
                cond.append("if (%s) %s <= 1'b0;" % (expr(clr), iq))
            if pre:
                cond.append("if (%s) %s <= 1'b1;" % (expr(pre), iq))
            cond.append("%s <= %s;" % (iq, nxt))
            body.append("        " + "\n        else ".join(cond))
        for p in outs:
            body.append("    assign %s = %s;" % (p.args[0], expr(p.attrs["function"])))
        body.append("endmodule")
        out += body + [""]
        n += 1
    with open(out_path, "w") as f:
        f.write("\n".join(out))
    print("wrote %d cell models to %s" % (n, out_path))


if __name__ == "__main__":
    main()
